export type Key = keyof (typeof DICT)['de'];
export type T = (key: Key) => string;

export function pickLang(search: string, navigatorLanguages: readonly string[] = []): Lang {
  const q = new URLSearchParams(search).get('lang');
  if (q === 'de' || q === 'en') return q;
  for (const l of navigatorLanguages) {
    if (l.toLowerCase().startsWith('de')) return 'de';
    if (l.toLowerCase().startsWith('en')) return 'en';
  }
  return 'de';
}

export function translator(lang: Lang): T {
  const table = DICT[lang];
  const fallback = DICT.de;
  return (key: Key) => table[key] ?? fallback[key];
}

const STATUS_KEYS: Record<string, Key> = {
  available: 'status_available',
  limited: 'status_limited',
  unavailable: 'status_unavailable',
};

/** Health status word, translated; unknown values are shown verbatim (never invented). */
export function statusLabel(t: T, status: string): string {
  const key = STATUS_KEYS[status];
  return key ? t(key) : status;
}

/**
 * Label for one editable config path. The dictionary may carry `setting_<path with dots replaced
 * by underscores>`; when it does not, the raw path is shown rather than an invented prose label.
 */
export function settingLabel(t: T, path: string): string {
  const key = `setting_${path.replace(/\./g, '_')}`;
  return key in DICT.de ? t(key as Key) : path;
}

